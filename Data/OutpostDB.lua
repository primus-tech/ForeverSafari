local function isSecret(v)
    if v == nil then return false end
    if issecretvalue and issecretvalue(v) then return true end
    if issecretpassphrase and issecretpassphrase(v) then return true end
    if issecretvariable and issecretvariable(v) then return true end
    local ok = pcall(function() local _ = (v == "") end)
    if not ok then return true end
    return false
end

local function ExtractNpcId(unit)
    if not unit or not UnitExists(unit) then return nil end
    local guid = UnitGUID(unit)
    if not guid or isSecret(guid) or type(guid) ~= "string" then return nil end
    local unitType, _, _, _, _, npcId = strsplit("-", guid)
    if (unitType == "Creature" or unitType == "Vehicle") and npcId then
        return tonumber(npcId)
    end
    local match = string.match(guid, "Creature%-[^%-]+%-[^%-]+%-[^%-]+%-[^%-]+%-(%d+)")
    if match then return tonumber(match) end
    return nil
end

