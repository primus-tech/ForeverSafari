-- Fast indexing caches
OutpostDB.BY_NPC_ID = {}
OutpostDB.BY_NAME = {}
OutpostDB.BY_ZONE = {}
OutpostDB.BY_TIER = { [1] = {}, [2] = {}, [3] = {}, [4] = {}, [5] = {} }
OutpostDB.LIST = {}

function OutpostDB:InitializeIndexes()
    self.BY_NPC_ID = {}
    self.BY_NAME = {}
    self.BY_ZONE = {}
    self.BY_TIER = { [1] = {}, [2] = {}, [3] = {}, [4] = {}, [5] = {} }
    self.LIST = {}

    for npcId, outpost in pairs(self.OUTPOSTS) do
        self.BY_NPC_ID[npcId] = outpost
        if outpost.name then
            self.BY_NAME[outpost.name] = outpost
        end
        if outpost.zone then
            self.BY_ZONE[outpost.zone] = self.BY_ZONE[outpost.zone] or {}
            table.insert(self.BY_ZONE[outpost.zone], outpost)
        end
        if outpost.tier and self.BY_TIER[outpost.tier] then
            table.insert(self.BY_TIER[outpost.tier], outpost)
        end
        table.insert(self.LIST, outpost)
    end

    -- Sort master list by tier, then level, then name
    table.sort(self.LIST, function(a, b)
        if (a.tier or 0) ~= (b.tier or 0) then
            return (a.tier or 0) < (b.tier or 0)
        end
        if (a.level or 0) ~= (b.level or 0) then
            return (a.level or 0) < (b.level or 0)
        end
        return (a.name or "") < (b.name or "")
    end)
end

function OutpostDB:GetOutpostByNpcId(npcId)
    if not npcId or type(npcId) ~= "number" then return nil end
    return self.BY_NPC_ID[npcId]
end

function OutpostDB:GetOutpostByName(name)
    if not name or isSecret(name) or type(name) ~= "string" then return nil end
    return self.BY_NAME[name]
end

function OutpostDB:GetOutpostByUnit(unit)
    unit = unit or "target"
    if not UnitExists(unit) or UnitIsDead(unit) or UnitIsPlayer(unit) then return nil end

    local npcId = ExtractNpcId(unit)
    if npcId and self.BY_NPC_ID[npcId] then
        return self.BY_NPC_ID[npcId]
    end

    local name = UnitName(unit)
    if name and not isSecret(name) and self.BY_NAME[name] then
        return self.BY_NAME[name]
    end

    return nil
end

function OutpostDB:GetAllOutposts()
    return self.LIST
end

function OutpostDB:GetOutpostsByZone(zone)
    if not zone or isSecret(zone) then return {} end
    return self.BY_ZONE[zone] or {}
end

function OutpostDB:GetOutpostsByTier(tier)
    return self.BY_TIER[tier] or {}
end

function OutpostDB:IsOutpostDefeated(outpostId)
    if not outpostId then return false end
    if not ForeverSafariDB or not ForeverSafariDB.defeatedOutposts then return false end
    return ForeverSafariDB.defeatedOutposts[outpostId] ~= nil
end

function OutpostDB:GetPlayerBadges()
    if not ForeverSafariDB or not ForeverSafariDB.badges then return {} end
    return ForeverSafariDB.badges
end

function OutpostDB:GenerateOutpostMatch(outpost)
    if not outpost then return nil end
    local SE = ns.StatEngine
    local team = {}
    local tplTeam = outpost.team or {}

    for i, petTpl in ipairs(tplTeam) do
        local baseStats = petTpl.baseStats or { hp = 40, atk = 22, def = 18, spd = 20 }
        local stats = SE and SE.CalculateStats and SE:CalculateStats(petTpl.element or "Beast", 0, false, baseStats) or { maxHP = 120, atk = 30, def = 25, spd = 25 }
        local companion = {
            id = string.format("outpost_pet_%s_%d", tostring(outpost.npcId), i),
            name = petTpl.name,
            nickname = petTpl.name,
            customNickname = petTpl.name,
            family = petTpl.family or "Beast",
            element = petTpl.element or "Beast",
            creatureType = petTpl.element or "Beast",
            displayId = petTpl.displayId or 903,
            level = petTpl.level or outpost.level or 10,
            maxHP = stats.maxHP,
            currentHP = stats.maxHP,
            hp = stats.maxHP,
            attack = stats.atk,
            atk = stats.atk,
            defense = stats.def,
            def = stats.def,
            speed = stats.spd,
            spd = stats.spd,
            moves = petTpl.moves or { 101, 102 },
            attunementRank = math.min(5, math.max(1, outpost.tier or 1)),
            isTrainerPet = true,
            isOutpostPet = true,
        }
        table.insert(team, companion)
    end

    return {
        isTrainer = true,
        isOutpost = true,
        outpostId = outpost.id,
        outpostData = outpost,
        trainerName = outpost.name,
        trainerTitle = outpost.title or "<Stable Master>",
        badge = outpost.badge,
        introQuote = outpost.introQuote or "Show me what your companions can do!",
        defeatQuote = outpost.defeatQuote or "Remarkable match! You have earned our outpost badge!",
        tokenReward = outpost.tokenReward or (15 + (outpost.tier or 1) * 5),
        team = team,
        activeSlot = 1,
    }
end

