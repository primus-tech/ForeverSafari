function OutpostDB:GetOutpostByUnit(unit)
    unit = unit or "target"
    if not UnitExists(unit) or UnitIsDead(unit) or UnitIsPlayer(unit) then return nil end

    local npcId = ExtractNpcId(unit)
    if npcId and self.BY_NPC_ID[npcId] then
        return self.BY_NPC_ID[npcId]
    end

    local name = UnitName(unit)
    if name and not isSecret(name) and self.BY_NAME[name] then
        return self.BY_NAME[name]
    end

    return nil
end

